import type { MapInfo } from "@ph/rules";

export interface MapImage {
  width: number;
  height: number;
  /** RGBA bytes straight from the PNG; province id + 1 is packed into R, G, B. 0 = water. */
  rgba: Uint8ClampedArray;
  /** Province index per pixel, -1 for water. Used for tapping. */
  ids: Int32Array;
  /**
   * Three bytes per pixel: terrain index (TERRAINS order); water depth band + 1,
   * or 64 + river size on land; river links (one bit per neighbour).
   */
  terrain: Uint8Array;
}

async function decode(url: string, width: number, height: number): Promise<Uint8ClampedArray> {
  const img = new Image();
  img.decoding = "async";
  img.src = new URL(url, document.baseURI).href;
  await img.decode();
  const canvas = document.createElement("canvas");
  canvas.width = width;
  canvas.height = height;
  const ctx = canvas.getContext("2d", { willReadFrequently: true })!;
  ctx.drawImage(img, 0, 0);
  return ctx.getImageData(0, 0, width, height).data;
}

/** Loads the province id and terrain images generated by tools/mapgen. */
export async function loadMapImage(map: MapInfo, provinceCount: number): Promise<MapImage> {
  const [data, terrainRgba] = await Promise.all([decode(map.provinceImage, map.width, map.height), decode(map.terrainImage, map.width, map.height)]);

  const ids = new Int32Array(map.width * map.height);
  for (let p = 0, i = 0; p < ids.length; p++, i += 4) {
    const v = (data[i]! << 16) | (data[i + 1]! << 8) | data[i + 2]!;
    // A browser that colour-manages the image would scramble ids; catch that loudly.
    if (v > provinceCount) throw new Error(`map image decoded wrongly at pixel ${p} (value ${v})`);
    ids[p] = v - 1;
  }
  const terrain = new Uint8Array(ids.length * 3);
  for (let p = 0; p < ids.length; p++) {
    terrain[p * 3] = terrainRgba[p * 4]!;
    terrain[p * 3 + 1] = terrainRgba[p * 4 + 1]!;
    terrain[p * 3 + 2] = terrainRgba[p * 4 + 2]!;
  }
  return { width: map.width, height: map.height, rgba: data, ids, terrain };
}
