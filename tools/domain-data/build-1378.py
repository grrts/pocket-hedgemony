"""Joins the region folders of the 1378 start into its scenario files (X-25, milestone 10 step 5).

Reads packages/rules/data/scenarios/1378/regions/<key>/ for every region that
scenario.json lists, in that order, and writes the scenario's own files beside
scenario.json, in the shapes of the 1444 folder:

  map-nations.json, map-owners.json, rulers.json, culture-start.json,
  relations.json, subjects.json, subjects-rulers.json, goals.json, map-to-catalogue.json,
  sleeping-realms.json, ports.json

Places that only the generated map can turn into province ids (sleeping
realms' capitals and homes, port towns) are written as [lon, lat] or owner-rule
selectors; `tools/mapgen/mapgen.ts 1378` then builds world/ and resolves them
there (world/sleeping-realms.json, world/ports.json).

Region data stays in the regions: fix a region's folder and re-run this, never
edit the joined files.

Run from the repository root:
  python3 tools/domain-data/build-1378.py [/mnt/project-files]
  node --experimental-strip-types tools/mapgen/mapgen.ts 1378
"""
import json, os, sys

files = sys.argv[1] if len(sys.argv) > 1 else "/mnt/project-files"
here = "packages/rules/data/scenarios"
src = f"{here}/1444"
out = f"{here}/1378"
load = lambda p: json.load(open(p, encoding="utf-8"))
scenario = load(f"{out}/scenario.json")
REGIONS = scenario["regions"]


def region(key, name, empty):
    path = f"{out}/regions/{key}/{name}"
    return load(path) if os.path.exists(path) else empty


def write(name, data, compact=False):
    with open(f"{out}/{name}", "w", encoding="utf-8") as f:
        if compact:
            f.write("[\n" + ",\n".join("  " + json.dumps(x, ensure_ascii=False) for x in data) + "\n]\n")
        else:
            f.write(json.dumps(data, indent=1, ensure_ascii=False) + "\n")


GENERATED = "Generated by tools/domain-data/build-1378.py from regions/ ({}). Do not edit by hand; fix the region and re-run."
gen = lambda what: GENERATED.format(what)

# 1444 province centres, for places a region gave as a 1444 province id.
GRID = load(f"{src}/world/map.json")
provinces_1444 = {p["id"]: p for p in load(f"{src}/world/provinces.json")}


def lonlat_1444(pid):
    p = provinces_1444[pid]
    return [round((p["x"] + 0.5) / GRID["pxPerDeg"] - 180, 3), round(GRID["latTop"] - (p["y"] + 0.5) / GRID["pxPerDeg"], 3)]


def place(c):
    return lonlat_1444(c) if isinstance(c, str) else c


# Map nations and owner rules: joined in region order, so first match wins across regions too.
nations, owners = [], []
for key in REGIONS:
    nations += region(key, "map-nations.json", [])
    owners += region(key, "map-owners.json", [])
nation_ids = {n["id"] for n in nations}
assert len(nation_ids) == len(nations), "a map nation is in two regions"
write("map-nations.json", nations, compact=True)
write("map-owners.json", owners, compact=True)

# Rulers, and the rulers the subjects context names.
rulers, subject_rulers = {}, {}
for key in REGIONS:
    rulers.update(region(key, "rulers.json", {"rulers": {}})["rulers"])
    subject_rulers.update(region(key, "subjects-rulers.json", {"rulers": {}})["rulers"])
write("rulers.json", {"$comment": gen("rulers.json") + " Each map realm's ruler on 20 September 1378 (REALM-233).", "rulers": rulers})
write("subjects-rulers.json", {"$comment": gen("subjects-rulers.json") + " The rulers the subjects context names on the start day.", "rulers": subject_rulers})

# Tongues and faiths: the 1444 tongues stay defined; regions add theirs.
culture_1444 = load(f"{src}/culture-start.json")
tongues, realms = dict(culture_1444["tongues"]), {}
for key in REGIONS:
    c = region(key, "culture-start.json", {"realms": {}})
    tongues.update(c.get("tongues", {}))
    realms.update(c["realms"])
write("culture-start.json", {"$comment": gen("culture-start.json") + " Court tongues, province tongues and faiths on the start day (CULT-094); the tongue list is the 1444 one plus the tongues the regions add.", "_provisional": culture_1444.get("_provisional", True), "tongues": tongues, "realms": realms})

# Relations and subjects are keyed by catalogue ids (SETUP-049). A region that wrote a map id whose
# record has another id (mamluks for mamluk, ottomans for ottoman) is read as that record.
setup_map = {k: v for k, v in load("packages/rules/data/domain/scenario-setup.json")["map_to_catalogue"].items() if k != "$comment"}
for key in REGIONS:
    setup_map.update(region(key, "map-to-catalogue.json", {"map_to_catalogue": {}})["map_to_catalogue"])
record_of = lambda i: setup_map.get(i) or i

# Relations and facts. A cross-region pair both regions recorded is kept once, from the first region.
relations, facts, entities, obedience = [], [], {}, {}
seen_rel, seen_fact = set(), set()
for key in REGIONS:
    r = region(key, "relations.json", {"relations": [], "facts": []})
    for x in r["relations"]:
        x = {**x, "source": record_of(x["source"]), "target": record_of(x["target"])}
        k = (x["type"], *sorted((x["source"], x["target"])))
        if x["id"] in seen_rel or k in seen_rel:
            continue
        seen_rel |= {x["id"], k}
        relations.append(x)
    for x in r.get("facts", []):
        x = {**x, "source": record_of(x["source"]), "target": record_of(x["target"])}
        k = (x["fact"], x["source"], x["target"])
        if x["id"] in seen_fact or k in seen_fact:
            continue
        seen_fact |= {x["id"], k}
        facts.append(x)
    for e in r.get("entities", []):
        entities.setdefault(e["id"], e)
    for realm, pope in (r.get("obedience") or {}).items():
        obedience.setdefault(realm, pope)
write("relations.json", {
    "schema_version": "1.0",
    "reference_date": "1378-09-20",
    "description": gen("relations.json") + " Relations and facts between realms on 20 September 1378, keyed by country-catalogue ids (new records by their research ids). A missing pair means nothing is recorded, not Neutral. entities: 1378 realms that are neither map nations nor catalogue records; obedience: the Pope each Catholic realm follows in the Western Schism (rome, avignon, or null while undecided).",
    "rules_file": "../config/relation-rules.json",
    "relations": relations,
    "facts": facts,
    "entities": list(entities.values()),
    "obedience": obedience,
})

# Subjects and stances; the catalogue-wide religious heads and playable subjects are joined too.
subjects_1444 = load(f"{src}/subjects.json")
subjects, stances, heads, playable = [], [], [], []
seen_sub, seen_stance = set(), set()
for key in REGIONS:
    s = region(key, "subjects.json", {"subjects": []})
    for row in s["subjects"]:
        row = [record_of(row[0]), record_of(row[1]), *row[2:]]
        if (row[0], row[1]) not in seen_sub:
            seen_sub.add((row[0], row[1]))
            subjects.append(row)
    for row in s.get("stances", []):
        row = [record_of(row[0]), record_of(row[1]), *row[2:]]
        k = tuple(sorted(row[:2]))
        if k not in seen_stance:
            seen_stance.add(k)
            stances.append(row)
    heads += [h for h in s.get("religious_heads", []) if h not in heads]
    playable += [p for p in s.get("playable_subjects", []) if p not in playable]
heads = heads or subjects_1444["religious_heads"]
with open(f"{out}/subjects.json", "w", encoding="utf-8") as f:
    f.write('{\n "$comment": ' + json.dumps(gen("subjects.json") + " The subject records and stances on the start day (SUBJ)."))
    f.write(',\n "subjects": [\n' + ",\n".join("  " + json.dumps(r, ensure_ascii=False) for r in subjects) + "\n ]")
    f.write(',\n "stances": [\n' + ",\n".join("  " + json.dumps(r, ensure_ascii=False) for r in stances) + "\n ]")
    f.write(',\n "religious_heads": ' + json.dumps(heads) + ',\n "playable_subjects": ' + json.dumps(sorted(playable)) + "\n}\n")

# Historical goals with their reasons (plan-1378 §2, EVT-085): every region's, in region order.
goals = []
for key in REGIONS:
    goals += region(key, "goals.json", {"goals": []})["goals"]
write("goals.json", {"$comment": gen("goals.json") + " Realms' historical goals on the start day (EVT-085), every region's in region order.", "goals": goals})

# Map ids whose catalogue record has another id (on top of scenario-setup.json's map_to_catalogue).
map_to_catalogue = {}
for key in REGIONS:
    m = region(key, "map-to-catalogue.json", {"map_to_catalogue": {}})["map_to_catalogue"]
    map_to_catalogue.update({k: v for k, v in m.items() if k != v})
write("map-to-catalogue.json", {"$comment": gen("map-to-catalogue.json") + " Map nations whose 1378 catalogue record has another id; they override scenario-setup.json's map_to_catalogue for this start.", "map_to_catalogue": map_to_catalogue})

# Sleeping realms: the regions' realms, then the 1444 ones history founds after 1444 that no region lists.
sleeping_1444 = load(f"{src}/world/sleeping-realms.json")
sleeping = []
for key in REGIONS:
    sleeping += region(key, "sleeping-realms.json", {"realms": []})["realms"]
listed = {s["id"] for s in sleeping} | nation_ids
for s in sleeping_1444["realms"]:
    if s["id"] not in listed:
        sleeping.append({**s, "carried_from_1444": True})
for s in sleeping:
    s["capital"] = place(s["capital"])
    s["home"] = [place(h) for h in s["home"]]
assert not ({s["id"] for s in sleeping} & nation_ids), "a realm is both on the map and asleep"
write("sleeping-realms.json", {
    "$comment": gen("sleeping-realms.json") + " Realms not yet born on 20 September 1378 (SETUP-080, X-24, X-25): the regions' realms, then the 1444 sleeping realms no region lists (carried_from_1444). Places are [lon, lat] or owner-rule selectors; tools/mapgen resolves them into world/sleeping-realms.json.",
    "spare_count": sleeping_1444["spare_count"],
    "realms": sleeping,
})

# Port towns, by [lon, lat]. Regions that list their towns give the holder; elsewhere the
# 1444 towns are kept and mapgen hands each to its province's 1378 owner (holder null).
ports_1444 = {t["name"]: t for t in load(f"{files}/naval/data/ports-1444.json")["ports"]}
towns, covered = [], set()
for key in REGIONS:
    p = region(key, "ports.json", None)
    if p is None:
        continue
    for t in p["towns"] + p.get("not_placed", []):
        ref = ports_1444.get(t["name"], {})
        lat, lon = t.get("lat", ref.get("lat")), t.get("lon", ref.get("lon"))
        if lat is None:
            continue
        covered.add(t["name"])
        towns.append({"name": t["name"], "lat": lat, "lon": lon, "holder": t["holder"], "tier": t["tier"], "shipyard": t["shipyard"], "source": t.get("source", "cat")})
for t in load(f"{src}/ports.json")["towns"]:
    if t["name"] in covered or t["name"] not in ports_1444:
        continue
    ref = ports_1444[t["name"]]
    towns.append({"name": t["name"], "lat": ref["lat"], "lon": ref["lon"], "holder": None, "tier": t["tier"], "shipyard": t["shipyard"], "source": t.get("source", "cat")})
with open(f"{out}/ports.json", "w", encoding="utf-8") as f:
    f.write('{\n "source": ' + json.dumps(gen("ports.json") + " Port towns of naval/data/ports-1444.json by lat and lon, with the 1378 holder where a region gives one; holder null takes its province's 1378 owner. tools/mapgen places them in world/ports.json."))
    f.write(',\n "towns": [\n' + ",\n".join("  " + json.dumps(t, ensure_ascii=False) for t in towns) + "\n ]\n}\n")

print(f"{len(nations)} map nations, {len(owners)} owner rules, {len(rulers)} rulers, {len(realms)} culture realms, "
      f"{len(relations)} relations, {len(facts)} facts, {len(subjects)} subjects, {len(sleeping)} sleeping realms, {len(towns)} port towns")
