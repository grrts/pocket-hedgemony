#!/usr/bin/env python3
"""Extracts each map realm's heritage and catalogue assessments.

Reads the heritage build (national-strengths/build/heritage-all.json), the
event tree's age names (packages/rules/data/domain/national-strengths.json),
the compact catalogue rows (scenario-setup-catalogue.json), the map's nations
(packages/rules/data/scenarios/1444/world/nations.json) and the map-to-catalogue rename table
(scenario-setup.json), and writes packages/rules/data/domain/
national-strengths-realms.json: for every map nation, its catalogue record id,
its 14 assessments with their confidence, and its heritage: birthright,
heydays (with their marks), burden (with its turned legacy) and the pool of
ambitions the campaign draws from (HER-078). The conditions go with them, so
the engine can evaluate heritage each month.

Run: python3 -I tools/domain-data/extract_realm_strengths.py [project-files-dir]
"""
import json
import pathlib
import sys

SRC = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "/mnt/project-files")
ROOT = pathlib.Path(__file__).resolve().parents[2]
DOMAIN = ROOT / "packages/rules/data/domain"


def load(path):
    return json.loads(path.read_text(encoding="utf-8"))


def part(p, keys):
    return {k: p[k] for k in keys if p.get(k) not in (None, "", [])}


def main():
    heritage = load(SRC / "national-strengths/build/heritage-all.json")["countries"]
    ages = {a["id"]: a["name"] for a in load(DOMAIN / "national-strengths.json")["ages"]}
    catalogue = load(DOMAIN / "scenario-setup-catalogue.json")
    rename = {k: v for k, v in load(DOMAIN / "scenario-setup.json")["map_to_catalogue"].items() if k != "$comment"}
    nations = load(ROOT / "packages/rules/data/scenarios/1444/world/nations.json")
    n = len(catalogue["dimensions"])

    realms = {}
    for nation in nations:
        cid = rename.get(nation["id"], nation["id"])
        row = catalogue["records"].get(cid) if cid else None
        h = heritage.get(cid) if cid else None
        out = {"catalogue": cid if row else None}
        if row:
            # Levels then confidences, one character each, in the catalogue's dimension order.
            codes = row.split("|")[5]
            out["assessments"] = codes[: 2 * n]
        if h:
            out["heritage"] = {
                "authored": bool(h.get("authored")),
                "birthright": part(h["birthright"], ["id", "name", "text", "why", "needs", "effects"]),
                "heydays": [
                    {**part(d, ["id", "name", "age", "text", "why", "wakes", "ends", "effects", "mark"]), "ageName": ages.get(d["age"], d["age"])}
                    for d in h.get("heydays") or []
                ],
                "burden": part(h["burden"], ["id", "name", "text", "why", "shed", "shed_text", "effects", "turned"]) if h.get("burden") else None,
                "ambitions": [
                    part(a, ["id", "name", "theme", "hint", "text", "historical", "window", "stir", "goal", "fail", "age", "legacy"])
                    for a in h.get("ambitions") or []
                ],
            }
        realms[nation["id"]] = out

    data = {
        "$comment": "Generated by tools/domain-data/extract_realm_strengths.py from national-strengths/build/heritage-all.json and the catalogue rows. Do not edit by hand.",
        "dimensions": catalogue["dimensions"],
        "level_codes": catalogue["level_codes"],
        "confidence_codes": catalogue["confidence_codes"],
        "realms": realms,
    }
    path = DOMAIN / "national-strengths-realms.json"
    text = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    path.write_text(text + "\n", encoding="utf-8")
    with_heritage = sum(1 for r in realms.values() if "heritage" in r)
    with_record = sum(1 for r in realms.values() if r["catalogue"])
    print(f"{path.relative_to(ROOT)}: {len(text) // 1024} KB, {len(realms)} realms, {with_record} with a record, {with_heritage} with heritage")


if __name__ == "__main__":
    main()
