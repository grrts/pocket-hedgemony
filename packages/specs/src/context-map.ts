import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { domainRoot } from "./features.ts";
import { readSpecs, type Seam } from "./catalogue.ts";

/**
 * Writes domain/context-map-seams.md and domain/open-questions.md from the
 * seams (section 11) and the decisions and open questions (section 13) of every spec, so the
 * two lists never drift from the specs. The hand-written domain/context-map.md
 * explains the map; these files are the full detail.
 */
const specs = readSpecs();
const known = new Set(specs.map((s) => s.context));

const pairs = new Map<string, Seam[]>();
for (const seam of specs.flatMap((s) => s.seams)) {
  const key = [seam.from, seam.to].sort().join(" ↔ ");
  pairs.set(key, [...(pairs.get(key) ?? []), seam]);
}

const out: string[] = [
  "# Seams between contexts (generated)",
  "",
  "Generated by `pnpm --filter @ph/specs context-map` from section 11 of every `spec.md`. Do not edit by hand.",
  "Each pair lists what both sides say. A pair named by only one side is marked **one-sided**: the other spec should confirm it.",
  "",
];
for (const [key, seams] of [...pairs].sort(([a], [b]) => a.localeCompare(b))) {
  const sides = new Set(seams.map((s) => s.from));
  const unknown = seams.some((s) => !known.has(s.to));
  out.push(`## ${key}${sides.size < 2 ? " (one-sided)" : ""}${unknown ? " (unknown context name)" : ""}`, "");
  out.push("| Said by | Other side is | Pattern | What crosses |", "|---|---|---|---|");
  for (const s of seams) out.push(`| ${s.from} | ${s.direction} | ${s.pattern} | ${s.crosses.replace(/\n/g, " ")} |`);
  out.push("");
}
writeFileSync(join(domainRoot, "context-map-seams.md"), out.join("\n"));

const openCount = specs.reduce((n, s) => n + s.openQuestions.length, 0);
const decidedCount = specs.reduce((n, s) => n + s.decisions.length, 0);
const oq: string[] = [
  "# Decisions and open questions (generated)",
  "",
  "Every gap or contradiction the domain specs found in the designs, collected from section 13 of each `spec.md` by `pnpm --filter @ph/specs context-map`. A question answered is a decision (`D-<CODE>-n`, which replaces `OQ-<CODE>-n`); the cross-context decisions and the rules used to decide are in [DECISIONS.md](DECISIONS.md).",
  "",
  "## Still open",
  "",
];
for (const s of specs.filter((s) => s.openQuestions.length)) for (const q of s.openQuestions) oq.push(`- **${q.id}** (${s.context}): ${q.text}`);
oq.push("", "## Decided", "");
for (const s of specs) {
  if (!s.decisions.length) continue;
  oq.push(`### ${s.title} (${s.context})`, "");
  for (const q of s.decisions) oq.push(`- **${q.id}**: ${q.text}`);
  oq.push("");
}
writeFileSync(join(domainRoot, "open-questions.md"), oq.join("\n"));
console.log(`${pairs.size} context pairs, ${decidedCount} decisions, ${openCount} open questions`);

// The index: one line per context. It carries no counts, so two branches that
// change different specs never both edit it and never conflict on it; the
// counts are printed below instead.
import { loadFeatures } from "./features.ts";
const features = loadFeatures();
const index: string[] = [
  "# Domain specs",
  "",
  "Every system of Pocket Hegemony as a bounded context: a domain spec (`spec.md`, requirements in EARS form) and Gherkin feature files (`features/`). Start with [context-map.md](context-map.md); the writing rules are in [CONVENTIONS.md](CONVENTIONS.md); every gap found and how it was decided is in [open-questions.md](open-questions.md). This index is generated by `pnpm --filter @ph/specs context-map`, which also prints each context's requirements, feature files, scenarios, decisions and open questions.",
  "",
  "| Context | Code | Features |",
  "|---|---|---|",
];
const sizes: Record<string, string | number>[] = [];
for (const s of specs) {
  const files = features.filter((f) => f.context === s.context);
  const scenarios = files.reduce((n, f) => n + f.pickles.length, 0);
  const reqs = s.requirements.filter((r) => s.code && r.startsWith(`${s.code}-`)).length;
  sizes.push({ context: s.context, requirements: reqs, features: files.length, scenarios, decided: s.decisions.length, open: s.openQuestions.length });
  index.push(`| [${s.title}](${s.context}/spec.md) | ${s.code} | [features](${s.context}/features/) |`);
}
index.push("");
writeFileSync(join(domainRoot, "README.md"), index.join("\n"));
console.table(sizes);
