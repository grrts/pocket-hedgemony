import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { domainRoot } from "./features.ts";
import { readSpecs, type Seam } from "./catalogue.ts";

/**
 * Writes domain/context-map-seams.md and domain/open-questions.md from the
 * seams (section 11) and open questions (section 13) of every spec, so the
 * two lists never drift from the specs. The hand-written domain/context-map.md
 * explains the map; these files are the full detail.
 */
const specs = readSpecs();
const known = new Set(specs.map((s) => s.context));

const pairs = new Map<string, Seam[]>();
for (const seam of specs.flatMap((s) => s.seams)) {
  const key = [seam.from, seam.to].sort().join(" ↔ ");
  pairs.set(key, [...(pairs.get(key) ?? []), seam]);
}

const out: string[] = [
  "# Seams between contexts (generated)",
  "",
  "Generated by `pnpm --filter @ph/specs context-map` from section 11 of every `spec.md`. Do not edit by hand.",
  "Each pair lists what both sides say. A pair named by only one side is marked **one-sided**: the other spec should confirm it.",
  "",
];
for (const [key, seams] of [...pairs].sort(([a], [b]) => a.localeCompare(b))) {
  const sides = new Set(seams.map((s) => s.from));
  const unknown = seams.some((s) => !known.has(s.to));
  out.push(`## ${key}${sides.size < 2 ? " (one-sided)" : ""}${unknown ? " (unknown context name)" : ""}`, "");
  out.push("| Said by | Other side is | Pattern | What crosses |", "|---|---|---|---|");
  for (const s of seams) out.push(`| ${s.from} | ${s.direction} | ${s.pattern} | ${s.crosses.replace(/\n/g, " ")} |`);
  out.push("");
}
writeFileSync(join(domainRoot, "context-map-seams.md"), out.join("\n"));

const oq: string[] = [
  "# Open questions and contradictions (generated)",
  "",
  "Every gap or contradiction the domain specs found in the designs, collected from section 13 of each `spec.md` by `pnpm --filter @ph/specs context-map`. Answer them in the design documents; the spec then drops the question.",
  "",
  `${specs.reduce((n, s) => n + s.openQuestions.length, 0)} questions across ${specs.length} contexts.`,
  "",
];
for (const s of specs) {
  oq.push(`## ${s.title} (${s.context})`, "");
  for (const q of s.openQuestions) oq.push(`- **${q.id}**: ${q.text}`);
  oq.push("");
}
writeFileSync(join(domainRoot, "open-questions.md"), oq.join("\n"));
console.log(`${pairs.size} context pairs, ${specs.reduce((n, s) => n + s.openQuestions.length, 0)} open questions`);

// The index: one line per context with its size, read from the specs and features.
import { loadFeatures } from "./features.ts";
const features = loadFeatures();
const index: string[] = [
  "# Domain specs",
  "",
  "Every system of Pocket Hegemony as a bounded context: a domain spec (`spec.md`, requirements in EARS form) and Gherkin feature files (`features/`). Start with [context-map.md](context-map.md); the writing rules are in [CONVENTIONS.md](CONVENTIONS.md); every gap found is in [open-questions.md](open-questions.md). This index is generated by `pnpm --filter @ph/specs context-map`.",
  "",
  "| Context | Code | Requirements | Feature files | Scenarios | Open questions |",
  "|---|---|---:|---:|---:|---:|",
];
let totals = [0, 0, 0, 0];
for (const s of specs) {
  const files = features.filter((f) => f.context === s.context);
  const scenarios = files.reduce((n, f) => n + f.pickles.length, 0);
  const reqs = s.requirements.filter((r) => s.code && r.startsWith(`${s.code}-`)).length;
  totals = [totals[0]! + reqs, totals[1]! + files.length, totals[2]! + scenarios, totals[3]! + s.openQuestions.length];
  index.push(`| [${s.title}](${s.context}/spec.md) | ${s.code} | ${reqs} | ${files.length} | ${scenarios} | ${s.openQuestions.length} |`);
}
index.push(`| **All ${specs.length} contexts** | | ${totals[0]} | ${totals[1]} | ${totals[2]} | ${totals[3]} |`, "", "Scenarios count each row of a Scenario Outline's examples.", "");
writeFileSync(join(domainRoot, "README.md"), index.join("\n"));
