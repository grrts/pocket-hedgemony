import data from "../../rules/data/domain/national-strengths-realms.json" with { type: "json" };
import west from "../../rules/data/domain/ambitions/common-west.json" with { type: "json" };
import east from "../../rules/data/domain/ambitions/east-africa.json" with { type: "json" };
import asia from "../../rules/data/domain/ambitions/asia-americas.json" with { type: "json" };
import type { Ambition, HeritageData } from "./domain/national-strengths/index.ts";

/**
 * Each map realm's national strengths and catalogue assessments
 * (national-strengths HER-080..083, scenario-setup SETUP-059): the realm's
 * matched catalogue record, its 14 starting assessments, and its heritage's
 * birthright, heydays and burden. Generated by
 * tools/domain-data/extract_realm_strengths.py; small enough for the client
 * to read without the whole catalogue.
 */

export type AssessmentLevel = "very_low" | "low" | "moderate" | "high" | "very_high" | "unknown";
export type AssessmentConfidence = "low" | "medium" | "high";

export interface RealmAssessment {
  dimension: string;
  level: AssessmentLevel;
  confidence: AssessmentConfidence;
}

export interface HeritageLine {
  id: string;
  name: string;
  text: string;
  why?: string;
  effects: { lever: string; value: number | boolean; [param: string]: unknown }[];
}

export interface RealmHeyday extends HeritageLine {
  age: string;
  ageName: string;
}

export interface RealmHeritage {
  authored: boolean;
  birthright: HeritageLine;
  heydays: RealmHeyday[];
  burden: HeritageLine | null;
}

/** The whole heritage as built: the parts above with their conditions, marks, turned legacy and the ambitions' pool (HER-078). */
interface Row {
  catalogue: string | null;
  assessments?: string;
  heritage?: RealmHeritage & Pick<HeritageData, "ambitions">;
}

export interface RealmStrengths {
  /** The matched catalogue record, or null where none matches (D-SETUP-1). */
  catalogue: string | null;
  /** In the catalogue's dimension order; empty without a record. */
  assessments: RealmAssessment[];
  /** Null for a realm the heritage build has no heritage for. */
  heritage: RealmHeritage | null;
}

const ROWS = data.realms as unknown as Record<string, Row>;
const LEVELS = data.level_codes as Record<string, AssessmentLevel>;
const CONFIDENCES = data.confidence_codes as Record<string, AssessmentConfidence>;

/** The 14 assessment dimensions, in the catalogue's order. */
export const ASSESSMENT_DIMENSIONS: readonly string[] = data.dimensions;
/** Dimensions where a higher level is worse for the realm. */
export const RISK_DIMENSIONS: readonly string[] = ["unrest_risk", "external_threat_exposure"];
/** A level as 1 (very low) to 5 (very high), 0 for unknown. */
export const LEVEL_RANK: Readonly<Record<AssessmentLevel, number>> = { unknown: 0, very_low: 1, low: 2, moderate: 3, high: 4, very_high: 5 };

/**
 * Ambitions written beside the heritage build (X-27, HER-014): common ones
 * every realm with heritage may draw, each with a requirement that makes it
 * fit, and more for each realm by its map id, many of them chained.
 */
type AmbitionsFile = { common?: Ambition[]; realms: Record<string, Ambition[]> };
const WRITTEN = [west, east, asia] as unknown as AmbitionsFile[];
export const COMMON_AMBITIONS: readonly Ambition[] = WRITTEN.flatMap((f) => f.common ?? []);
const EXTRA: Record<string, Ambition[]> = {};
for (const f of WRITTEN) for (const [id, list] of Object.entries(f.realms)) (EXTRA[id] ??= []).push(...list);
/** The ambitions written for one map realm beyond the heritage build. */
export const extraAmbitions = (mapId: string): readonly Ambition[] => EXTRA[mapId] ?? [];

const EMPTY: RealmStrengths = { catalogue: null, assessments: [], heritage: null };

/** A map realm's catalogue record, assessments and heritage. */
export function realmStrengths(mapId: string): RealmStrengths {
  const row = ROWS[mapId];
  if (!row) return EMPTY;
  const n = ASSESSMENT_DIMENSIONS.length;
  const codes = row.assessments ?? "";
  return {
    catalogue: row.catalogue,
    assessments: codes ? ASSESSMENT_DIMENSIONS.map((dimension, i) => ({ dimension, level: LEVELS[codes[i]!]!, confidence: CONFIDENCES[codes[n + i]!]! })) : [],
    heritage: row.heritage ?? null,
  };
}

/** A map realm's heritage as the national-strengths library reads it (conditions included), or null; its id is the catalogue record's. */
export function realmHeritageData(mapId: string): HeritageData | null {
  const row = ROWS[mapId];
  if (!row?.heritage) return null;
  const h = row.heritage as unknown as HeritageData;
  const ambitions = [...(h.ambitions ?? []), ...extraAmbitions(mapId), ...COMMON_AMBITIONS];
  return { id: row.catalogue ?? mapId, authored: row.heritage.authored, birthright: h.birthright, heydays: h.heydays, ambitions, burden: h.burden ?? null };
}

/** The id heritage conditions use for a map realm: its catalogue record's, else its own (D-SETUP-1). */
export function conditionId(mapId: string): string {
  return ROWS[mapId]?.catalogue ?? mapId;
}

/** One assessment of a map realm; unknown where it has no record. */
export function realmAssessment(mapId: string, dimension: string): AssessmentLevel {
  const i = ASSESSMENT_DIMENSIONS.indexOf(dimension);
  if (i < 0) throw new Error(`unknown assessment ${dimension}`);
  const code = ROWS[mapId]?.assessments?.[i];
  return code ? LEVELS[code]! : "unknown";
}

/** A realm's administrative capacity as 1 (very low) to 5 (very high), 0 for unknown: how far its rule reaches. */
export function adminCapacityRank(mapId: string): number {
  return LEVEL_RANK[realmAssessment(mapId, "administrative_capacity")];
}
